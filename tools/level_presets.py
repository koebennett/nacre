#!/usr/bin/env python3
"""Render every factory preset, loudness-match it, sanity-check it, and embed the
library into engine/FactoryPresets.cpp.

Each preset is played with the audition phrase that suits its category (a held
chord for pads, a bass line for basses...), measured with ITU-R BS.1770 integrated
loudness, and given the master volume that brings it to TARGET_LUFS - while never
letting the phrase peak above PEAK_CEIL. Presets that are silent, non-finite, have
DC offset or never decay are reported and fail the build.
"""
import json, os, re, subprocess, sys, math
from concurrent.futures import ThreadPoolExecutor

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'tools'))
import make_presets

TOOL = os.path.join(ROOT, 'build-tools', 'nacre_render')
TARGET_LUFS = -16.0
PEAK_CEIL = 0.708          # -3 dBFS
PEAK_NORMALISED = {'Percussion'}
SUSTAINING = {'Drones', 'Atmospheres', 'FX & Risers', 'Pads', 'Choirs & Vox', 'Strings'}

def stats(phrase, files):
    out = subprocess.run([TOOL, 'stats', phrase] + files, capture_output=True, text=True, check=True).stdout
    return [json.loads(l) for l in out.splitlines() if l.startswith('{')]

def main():
    lst = make_presets.build()
    groups = {}
    for cat, name, path, phrase in lst: groups.setdefault(phrase, []).append(path)
    jobs = []
    for phrase, files in groups.items():
        for i in range(0, len(files), 12): jobs.append((phrase, files[i:i + 12]))
    results = {}
    with ThreadPoolExecutor(max_workers=os.cpu_count() or 2) as ex:
        for res in ex.map(lambda j: stats(*j), jobs):
            for r in res: results[r['file']] = r
    problems, report = [], []
    for cat, name, path, phrase in lst:
        r = results[path]
        if not r['finite']: problems.append('%s: non-finite output' % name); continue
        if r['lufs'] < -60: problems.append('%s: silent (%.1f LUFS)' % (name, r['lufs'])); continue
        if abs(r['dc']) > 0.005: problems.append('%s: DC offset %.4f' % (name, r['dc']))
        if r['tail'] > 0.5 * r['peak'] and cat not in SUSTAINING: problems.append('%s: does not decay (tail %.3f)' % (name, r['tail']))
        gain_db = TARGET_LUFS - r['lufs'] if cat not in PEAK_NORMALISED else 99.0
        peak_db = 20 * math.log10(max(r['peak'], 1e-9))
        gain_db = min(gain_db, 20 * math.log10(PEAK_CEIL) - peak_db)
        if gain_db > 12: problems.append('%s: needs %+.1f dB, more than the +12 dB range' % (name, gain_db)); gain_db = 12
        gain_db = max(gain_db, -48)
        txt = open(path).read()
        txt = re.sub(r'^master_gain=.*\n', '', txt, flags=re.M) + 'master_gain=%.2f\n' % gain_db
        open(path, 'w').write(txt)
        report.append((cat, name, r['lufs'], peak_db, gain_db, r['rt'], r['corr']))
    # embed
    lines = ['// Generated by tools/level_presets.py - do not edit by hand.', '#include "Preset.h"', 'namespace nacre {',
             'static const FactoryPreset kFactory[] = {']
    def cstr(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n"\n    "') + '"'
    for cat, name, path, phrase in lst:
        txt = open(path).read()
        tags = re.search(r'^@tags=(.*)$', txt, re.M).group(1)
        lines.append('  { %s, %s, %s,\n    %s },' % (cstr(name), cstr(cat), cstr(tags), cstr(txt)))
    lines += ['};', 'const FactoryPreset* factoryPresets(int& count) { count = (int) (sizeof(kFactory) / sizeof(kFactory[0])); return kFactory; }', '}']
    open(os.path.join(ROOT, 'engine', 'FactoryPresets.cpp'), 'w').write('\n'.join(lines) + '\n')

    gains = [r[4] for r in report]
    worst_rt = max(report, key=lambda r: r[5])
    print('%d presets levelled. gain range %+.1f .. %+.1f dB, slowest %s at %.2fx real time (2x oversampled)' %
          (len(report), min(gains), max(gains), worst_rt[1], worst_rt[5]))
    cap = [r for r in report if (TARGET_LUFS - r[2]) > r[4] + 0.5]
    print('%d presets are peak-limited below the loudness target (percussive material)' % len(cap))
    with open(os.path.join(ROOT, 'build-tools', 'levels.tsv'), 'w') as f:
        for r in report: f.write('%s\t%s\t%.1f\t%.1f\t%+.1f\t%.3f\t%.2f\n' % r)
    if problems:
        print('\nPROBLEMS:'); [print('  ' + p) for p in problems]; sys.exit(1)
    print('no problems found')

if __name__ == '__main__':
    main()
